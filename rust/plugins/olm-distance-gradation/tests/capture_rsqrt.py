"""Capture the CPU's RSQRTSS lookup, independently validate low bits/exponents.

The AEX's native IPP sqrt body at RVA 0x2f1e20 executes the same RSQRT
operation followed by explicit FMA refinement. No image output is fitted.
"""
import ctypes
import hashlib
import json
from pathlib import Path
import random
import struct
import sys

crate = Path(__file__).resolve().parents[1]
module = Path(sys.argv[1]).resolve()
lib = ctypes.WinDLL(str(module))
fn = lib.olm_update_rsqrt_v1
fn.argtypes, fn.restype = [ctypes.c_float], ctypes.c_float
def f(bits): return struct.unpack('<f', struct.pack('<I', bits))[0]
def bits(x): return struct.unpack('<I', struct.pack('<f', x))[0]
table = [bits(fn(f((e << 23) | (m << 11)))) for e in (127,128) for m in range(4096)]
def emulate(b):
    e = (b >> 23) & 255
    parity = (e - 127) & 1
    return table[parity*4096 + ((b & 0x7fffff) >> 11)] - ((e-127-parity)//2 << 23)
checked = 0
for e in (127,128):
    for m in range(4096):
        for low in (0,1,1023,1024,2047):
            b = (e<<23) | (m<<11) | low
            assert bits(fn(f(b))) == emulate(b), hex(b)
            checked += 1
rng = random.Random(20261113)
for _ in range(100000):
    b = (rng.randrange(1,255)<<23) | rng.randrange(1<<23)
    assert bits(fn(f(b))) == emulate(b), hex(b)
    checked += 1
text = '// OLM-internal native RSQRT lookup; generated by tests/capture_rsqrt.py.\n'
text += 'pub const RSQRT: [u32; 8192] = [\n'
for i in range(0,len(table),8):
    text += '    ' + ', '.join(f'0x{x:08x}' for x in table[i:i+8]) + ',\n'
text += '];\n'
(crate/'src/rsqrt_table.rs').write_text(text)
(crate/'tests/rsqrt-provenance.json').write_text(json.dumps({
    'instruction':'RSQRTSS (same per-lane result as RSQRTPS)',
    'plugin_sqrt_rva':'0x2f1e20', 'seed':20261113,
    'validated_vectors':checked, 'module_sha256':hashlib.sha256(module.read_bytes()).hexdigest(),
    'table_sha256':hashlib.sha256(text.encode()).hexdigest(),
    'domain':'positive finite normal f32; 8192 table bins, five low-mantissa probes per bin and 100000 random exponent/mantissa probes',
    'qualification':'This CPU profile only; no claim that other x86 implementations use the same approximation.'},indent=2))
print(f'{checked} instruction vectors exact; wrote 8192-entry portable table')
