#!/usr/bin/env python3
"""Regenerate only the algorithm's used table fields from the pinned local DLL.
OLM-internal; no executable code, padding, or unused table fields are emitted.
Requires pefile (available in MAIN tools/emulation/.venv).
"""
import hashlib
from pathlib import Path
import struct
import pefile
DLL=Path.home()/'.cache/olm-emu/ucrt/10.0.28000.2705/ucrtbase.dll'
assert hashlib.sha256(DLL.read_bytes()).hexdigest()=='385a6d73a50063a4c760bdb2ee59e575de7ff350a2e3b214ea491d08358484f3'
p=pefile.PE(str(DLL))
def d(r): return struct.unpack('<d',p.get_data(r,8))[0].hex()
lines=['/* OLM-internal. Generated by pow_extract.py; provenance: pow.md. */',
       'static const double pow_log[128][3] = {']
for i in range(128):
 lines.append(' {'+', '.join(d(0x105b18+32*i+o) for o in [0,16,24])+'},')
lines+=['};','static const struct { double tail; uint64_t scale; } pow_exp[256] = {']
for i in range(256):
 u=struct.unpack('<Q',p.get_data(0x106be8+16*i,8))[0]
 lines.append(' {'+d(0x106be0+16*i)+f', UINT64_C(0x{u:016x})'+'},')
lines+=['};','']
Path(__file__).with_name('pow_tables.h').write_text('\n'.join(lines))
